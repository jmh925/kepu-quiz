def main():
    text = io.open(P, encoding="utf-8").read()
    added = 0
    for anchor, sent, no, name, fn in INSERTS:
        block = ""
        if sent:
            block += "\n" + sent + "\n"
        block += "\n![%s %s](%s)\n" % (no, name, fn)

        if anchor.startswith("### ") or anchor.startswith("![") :
            # 以标题或上一条图注为锚点：直接在其后追加
            if anchor not in text:
                print("  [FAIL] 锚点未找到：%s" % anchor[:40])
                continue
            text = text.replace(anchor, anchor + block, 1)
        else:
            if anchor not in text:
                print("  [FAIL] 锚点未找到：%s…" % anchor[:36])
                continue
            if text.count(anchor) > 1:
                print("  [WARN] 锚点不唯一，仍按首次插入：%s…" % anchor[:36])
            text = text.replace(anchor, anchor + block, 1)
        added += 1
        print("  [OK  ] %s %s -> %s…" % (no, name, (sent[:22] + "…") if sent else "接上一图之后"))

    io.open(P, "w", encoding="utf-8", newline="\n").write(text)
    print()
    print("插入 %d 处，第5章现 %d 字" % (added, len(re.sub(r"\s", "", text))))
    return 0


if __name__ == "__main__":
    sys.exit(main())
