def verify():
    bad = 0
    for ch, sec, old, new, why, st, key in ITEMS:
        if old.startswith("（原文无"):
            continue
        if old.startswith("「"):
            continue
        if old.startswith("该页"):
            continue
        o = re.sub(r"\s", "", old)
        # 原文很长时只校验前 30 字
        probe = o[:30] if len(o) > 30 else o
        probe = probe.replace("……", "")
        probe = probe.split("……")[0]
        if probe and probe not in PDFF:
            print("  [原文未匹配] %s / %s：%s" % (ch, sec, probe[:34]))
            bad += 1
    return bad


