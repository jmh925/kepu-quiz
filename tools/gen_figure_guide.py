def extract_tables(text):
    """抓取「表X-Y 名称」标题及其后的 pipe 表格。"""
    lines = text.split("\n")
    out = []
    i = 0
    while i < len(lines):
        m = re.match(r"^(表[ⅠⅡ]?[-\u2014]?\d+(?:-\d+)?)\s*(.+)$", lines[i].strip())
        if m:
            cap_no, cap_name = m.group(1).replace("\u2014", "-"), m.group(2).strip()
            j = i + 1
            while j < len(lines) and not lines[j].strip():
                j += 1
            if j < len(lines) and lines[j].strip().startswith("|"):
                block = []
                while j < len(lines) and lines[j].strip().startswith("|"):
                    block.append(lines[j].rstrip())
                    j += 1
                out.append((cap_no, cap_name, block))
                i = j
                continue
        i += 1
    return out


